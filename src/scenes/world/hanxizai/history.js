export function recordAnswer(answers, chapter, option) {
  const mystery = MYSTERIES[chapter];
  if (!mystery || !Number.isInteger(option) || !mystery.options[option])
    return answers;
  const previous = answers[mystery.id];
  return {
    ...answers,
    [mystery.id]: {
      choice: option,
      correct: option === mystery.answer,
      attempts: (previous?.attempts ?? 0) + 1,
    },
  };
}

